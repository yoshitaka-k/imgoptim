use std::{fs, path::Path};

/// フォントのパスを取得
/// * `path` - フォントのパス
/// * `return` - フォントのパス
fn include_font_path(path: &str) -> String {
    if path.starts_with("assets/") {
        format!("concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{}\")", path)
    } else {
        panic!("font path must start with 'assets/' (was: {})", path);
    }
}

/// 識別子として使える名前に変換
/// 空白や記号を『 _ 』に変換して大文字にする
/// * `font_name` - フォント名
/// * `return` - 識別子として使える名前
fn to_const_name(font_name: &str) -> String {
    font_name.chars()
             .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
             .collect::<String>()
             .to_uppercase()
}

/// assets/fonts 内のフォントの一覧を生成
/// * `fonts_dir` - フォントディレクトリのパス
/// * `out_dir` - 出力ディレクトリのパス
pub(crate) fn generate_fonts_generated(fonts_dir: &Path, out_dir: &String) {
    let mut font_names: Vec<String> = Vec::new();
    for entry in fs::read_dir(fonts_dir).expect("failed to read assets/fonts") {
        let entry = entry.expect("failed to read directory entry");
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) != Some("ttf") {
            continue;
        }

        let font_name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("invalid font filename")
            .to_string();
        font_names.push(font_name);
    }

    font_names.sort();

    let mut output = String::from("// @generated by build.rs — do not edit\n\n");

    for font_name in &font_names {
        let const_name = to_const_name(font_name);
        let asset_path = format!("assets/fonts/{font_name}.ttf");
        output.push_str(&format!(
            "pub const {const_name}: &[u8] = include_bytes!({});\n",
            include_font_path(&asset_path),
        ));
    }

    output.push_str("pub const FONTS: &[(&str, &[u8])] = &[\n");
    for font_name in &font_names {
        let const_name = to_const_name(font_name);
        output.push_str(&format!("(\"{font_name}\", {const_name}),\n"));
    }
    output.push_str("];\n");

    println!("cargo:warning=generated fonts: {:?}", font_names);

    let out_path = Path::new(out_dir).join("fonts_generated.rs");
    fs::write(&out_path, output).expect("failed to write generated fonts");
}
